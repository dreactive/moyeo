from typing import Awaitable, Callable, Protocol


class AgentPort(Protocol):
    async def run(self, task: dict, emit_trace: Callable[[dict], Awaitable[None]]) -> dict: ...
    async def execute_tool(self, name: str, arguments: dict, context: dict) -> dict: ...
    async def aclose(self) -> None: ...

class PreparedAgentPort(AgentPort, Protocol):
    async def extract(self, task: dict, previous: dict | None = None) -> dict: ...
    async def run_prepared(self, task: dict, prepared: dict,
                           emit_trace: Callable[[dict], Awaitable[None]],
                           is_current: Callable[[], bool] | None = None) -> dict: ...
